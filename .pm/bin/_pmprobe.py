"""The probe of the emulator's services (issue 517): its table, its requests, their signing and the reading of the
answers. Not a command; pm-probe-services imports it, and its tests import it.

The table is .pm/bin/probe-services.json. Its `services` are written by hand, one per key of the pm's board
(.pm/product/services.md), in the board's order: the key, the board's name, the AWS CLI service models that serve
it (`models`, zero or more) and, for a key with none, why (`none`). Its `models` are generated by
`pm-probe-services table` from the AWS CLI's own model files on the machine (botocore/data under the CLI's
install, read as files, nothing run and nothing sent): per model its API version, signing name, protocol, JSON
target and version, and `ops`, the read operations it can send: a `List*`, `Describe*` or `Get*` operation whose
every required input member is an integer limit (an integer whose name says max, limit or page size), filled with
10 held to its range, or a string enum, filled with its first value (the pm's decision on issue 517, Q1 b). No other verb enters the table, so no request of the probe writes.

A request goes to https://127.0.0.1:<port>/ only, signed with SigV4 for us-east-1 and the model's signing name.
An answer is read as: 2xx `answered`; 501 `not implemented`; 404 with error type UnknownService `refused` (the
emulator registers no service of that signing name); anything else `error` with its status and error code; no
answer `no answer` with the kind of failure.
"""
import datetime
import hashlib
import hmac
import json
import os
import pathlib
import re
import urllib.parse

HERE = pathlib.Path(__file__).resolve().parent
TABLE = HERE / "probe-services.json"
REGION = "us-east-1"
VERBS = ("List", "Describe", "Get")
# The protocols the probe speaks, in the order a model's own list is read: the AWS CLI picks JSON over CBOR for
# a model that offers both (seen for cloudwatch), and every model that offers CBOR offers JSON too.
PROTOCOLS = ("json", "rest-json", "rest-xml", "query", "ec2")
LIMIT = 10
LIMIT_NAME = re.compile(r"max|limit|pagesize", re.I)  # an integer member filled is a limit by its name
MESSAGE_MAX = 200
BODY_MAX = 64 * 1024


# ------------------------------------------------------------------------------------------------- the table

def latest_model(models_dir, name):
    """The newest service-2.json of model `name` under a botocore data folder, or None."""
    d = pathlib.Path(models_dir) / name
    found = sorted(d.glob("*/service-2.json")) if d.is_dir() else []
    return found[-1] if found else None


def protocol_of(meta):
    offered = meta.get("protocols") or [meta.get("protocol")]
    return next((p for p in offered if p in PROTOCOLS), None)


def fill_of(shapes, member_name, member):
    """The value of a required member, or None when the probe does not fill that kind."""
    shape = shapes.get(member.get("shape"), {})
    if shape.get("type") in ("integer", "long") and LIMIT_NAME.search(member_name):
        low, high = shape.get("min"), shape.get("max")
        value = LIMIT
        if high is not None:
            value = min(value, int(high))
        if low is not None:
            value = max(value, int(low))
        return value
    if shape.get("type") == "string" and shape.get("enum"):
        return shape["enum"][0]
    return None


def op_entry(model, name, op, protocol):
    """The table entry of operation `name`, or None when the probe cannot send it without an argument of its own."""
    if not name.startswith(VERBS):
        return None
    shapes = model["shapes"]
    http = op.get("http", {})
    entry = dict(name=name, method=http.get("method", "POST"), uri=http.get("requestUri", "/"), fill=[])
    inp = op.get("input")
    if inp:
        shape = shapes.get(inp["shape"], {})
        members = shape.get("members", {})
        for m in shape.get("required", []):
            member = members.get(m)
            if member is None:
                return None
            value = fill_of(shapes, m, member)
            if value is None:
                return None
            location = member.get("location", "body")
            if protocol == "rest-xml" and location == "body":
                return None  # an XML payload is not built
            if protocol == "ec2":
                wire = member.get("queryName") or (member.get("locationName") or m)[:1].upper() + \
                    (member.get("locationName") or m)[1:]
            else:
                wire = member.get("locationName", m)
            entry["fill"].append(dict(member=m, location=location, name=wire, value=value))
    labels = re.findall(r"\{([^}]+?)\+?\}", entry["uri"].split("?")[0])
    if protocol in ("rest-json", "rest-xml"):
        filled = {f["name"] for f in entry["fill"] if f["location"] == "uri"}
        if any(label not in filled for label in labels):
            return None
    return entry


def model_entry(models_dir, name):
    """The generated table entry of model `name`."""
    path = latest_model(models_dir, name)
    if path is None:
        return dict(missing="no such model among the AWS CLI's files")
    model = json.loads(path.read_text())
    meta = model["metadata"]
    protocol = protocol_of(meta)
    entry = dict(api_version=meta.get("apiVersion"), signing_name=meta.get("signingName") or meta.get("endpointPrefix"),
                 protocol=protocol, offered=meta.get("protocols") or [meta.get("protocol")])
    if meta.get("targetPrefix"):
        entry["target_prefix"] = meta["targetPrefix"]
    if meta.get("jsonVersion"):
        entry["json_version"] = meta["jsonVersion"]
    if protocol is None:
        entry["ops"] = []
        return entry
    ops = [op_entry(model, n, model["operations"][n], protocol) for n in sorted(model["operations"])]
    entry["ops"] = [o for o in ops if o is not None]
    return entry


def build(table, models_dir, source):
    """The table with its `models` generated anew from `models_dir`; the hand-written `services` are kept.
    `models_from` names the folder and the sha256 of the model files read (name, version folder and bytes)."""
    names = sorted({m for s in table["services"] for m in s.get("models", [])})
    digest = hashlib.sha256()
    for n in names:
        path = latest_model(models_dir, n)
        if path is not None:
            digest.update(f"{n}/{path.parent.name}\n".encode() + path.read_bytes())
    out = dict(table)
    out["models_from"] = dict(folder=source, sha256=digest.hexdigest())
    out["models"] = {n: model_entry(models_dir, n) for n in names}
    return out


def board_keys(text):
    """The keys of the board's service rows: the backquoted third cell of a row whose first cell is a number."""
    keys = []
    for line in text.splitlines():
        cells = [c.strip() for c in line.split("|")]
        if len(cells) > 4 and cells[1].isdigit():
            keys.append(cells[3].strip("`"))
    return keys


def load_table(path=TABLE):
    return json.loads(pathlib.Path(path).read_text())


# ------------------------------------------------------------------------------------------------- requests

def _q(text, safe="-_.~"):
    return urllib.parse.quote(str(text), safe=safe)


def request_of(model, op):
    """(method, path, query pairs, headers, body bytes) of one table operation, before signing. The query pairs
    are already encoded as they are sent."""
    protocol = model["protocol"]
    headers, query, body = {}, [], b""
    fills = op.get("fill", [])
    if protocol == "json":
        headers["Content-Type"] = f"application/x-amz-json-{model.get('json_version', '1.0')}"
        headers["X-Amz-Target"] = f"{model['target_prefix']}.{op['name']}"
        body = json.dumps({f["name"]: f["value"] for f in fills}, separators=(",", ":")).encode()
        return "POST", "/", query, headers, body
    if protocol in ("query", "ec2"):
        headers["Content-Type"] = "application/x-www-form-urlencoded; charset=utf-8"
        pairs = [("Action", op["name"]), ("Version", model["api_version"])] + [(f["name"], f["value"]) for f in fills]
        body = "&".join(f"{_q(k)}={_q(v)}" for k, v in pairs).encode()
        return "POST", "/", query, headers, body
    # rest-json and rest-xml
    uri = op["uri"]
    path, _, literal = uri.partition("?")
    for f in fills:
        if f["location"] == "uri":
            path = path.replace("{" + f["name"] + "+}", _q(f["value"], safe="/-_.~"))
            path = path.replace("{" + f["name"] + "}", _q(f["value"]))
    for part in filter(None, literal.split("&")):
        k, _, v = part.partition("=")
        query.append((_q(urllib.parse.unquote(k)), _q(urllib.parse.unquote(v))))
    for f in fills:
        if f["location"] == "querystring":
            query.append((_q(f["name"]), _q(f["value"])))
        elif f["location"] == "header":
            headers[f["name"]] = str(f["value"])
    body_fills = {f["name"]: f["value"] for f in fills if f["location"] == "body"}
    if protocol == "rest-json" and (body_fills or op["method"] not in ("GET", "HEAD", "DELETE")):
        headers["Content-Type"] = "application/json"
        body = json.dumps(body_fills, separators=(",", ":")).encode()
    return op["method"], path or "/", query, headers, body


def _hmac(key, text):
    return hmac.new(key, text.encode(), hashlib.sha256).digest()


def sign(method, host, path, query, headers, body, access_key, secret_key, service, region=REGION, when=None,
         double_encode=True, content_sha=True):
    """The headers of a SigV4-signed request: `headers` plus host, x-amz-date, x-amz-content-sha256 and
    authorization. `query` is a list of encoded (key, value) pairs. The path is encoded once more for the
    canonical request (every service but S3, `double_encode`); `content_sha` false leaves x-amz-content-sha256
    out, as the AWS signature test suite does."""
    when = when or datetime.datetime.now(datetime.timezone.utc)
    amz_date = when.strftime("%Y%m%dT%H%M%SZ")
    day = amz_date[:8]
    payload = hashlib.sha256(body).hexdigest()
    signed = {k.lower(): " ".join(str(v).split()) for k, v in headers.items()}
    signed.update({"host": host, "x-amz-date": amz_date})
    if content_sha:
        signed["x-amz-content-sha256"] = payload
    names = sorted(signed)
    canonical_path = _q(path, safe="/-_.~%") if not double_encode else _q(path, safe="/-_.~")
    canonical = "\n".join([
        method,
        canonical_path,
        "&".join(f"{k}={v}" for k, v in sorted(query)),
        "".join(f"{n}:{signed[n]}\n" for n in names),
        ";".join(names),
        payload,
    ])
    scope = f"{day}/{region}/{service}/aws4_request"
    to_sign = "\n".join(["AWS4-HMAC-SHA256", amz_date, scope, hashlib.sha256(canonical.encode()).hexdigest()])
    key = _hmac(_hmac(_hmac(_hmac(("AWS4" + secret_key).encode(), day), region), service), "aws4_request")
    signature = hmac.new(key, to_sign.encode(), hashlib.sha256).hexdigest()
    out = dict(headers)
    out.update({"Host": host, "X-Amz-Date": amz_date})
    if content_sha:
        out["X-Amz-Content-Sha256"] = payload
    out.update({"Authorization": f"AWS4-HMAC-SHA256 Credential={access_key}/{scope}, SignedHeaders={';'.join(names)}, "
                                 f"Signature={signature}"})
    return out


# ------------------------------------------------------------------------------------------------- answers

def error_of(status, headers, body):
    """(code, message) of an answer, each '' when the answer does not say."""
    code = ""
    for k, v in headers.items():
        if k.lower() == "x-amzn-errortype":
            code = v.split(":")[0]
    text = body[:BODY_MAX].decode("utf-8", "replace")
    message = ""
    try:
        doc = json.loads(text)
    except ValueError:
        doc = None
    if isinstance(doc, dict):
        code = code or str(doc.get("__type") or doc.get("code") or doc.get("Code") or "")
        message = str(doc.get("message") or doc.get("Message") or "")
    else:
        m = re.search(r"<Code>([^<]*)</Code>", text)
        code = code or (m.group(1) if m else "")
        m = re.search(r"<Message>([^<]*)</Message>", text)
        message = m.group(1) if m else ""
    code = code.split("#")[-1]
    return code[:MESSAGE_MAX], " ".join(message.split())[:MESSAGE_MAX]


def outcome_of(status, headers, body):
    """The probe's reading of one answer: {outcome, status, code, message}."""
    if 200 <= status < 300:
        return dict(outcome="answered", status=status)
    code, message = error_of(status, headers, body)
    if status == 501:
        outcome = "not implemented"
    elif status == 404 and code == "UnknownService":
        outcome = "refused"
    else:
        outcome = "error"
    return dict(outcome=outcome, status=status, code=code, message=message)


def _names(ops, n=3):
    shown = ", ".join(o["op"] for o in ops[:n])
    return shown + (f" +{len(ops) - n} more" if len(ops) > n else "")


def _with_code(ops, n=3):
    shown = ", ".join(f"{o['op']} {o.get('status') or ''} {o.get('code') or ''}".strip() for o in ops[:n])
    return shown + (f" +{len(ops) - n} more" if len(ops) > n else "")


def service_result(entry, model_results):
    """The result of one board key: {result, summary} from its models' results ([{model, result?, ops}])."""
    if not entry.get("models"):
        return "no API", f"no API: {entry.get('none', 'no AWS CLI model')}"
    ops = []
    for m in model_results:
        for o in m.get("ops", []):
            ops.append(dict(o, op=o["op"] if len(model_results) == 1 else f"{m['model']}:{o['op']}"))
    if not ops:
        return "no read call", "no read call without an argument; left to its plan"
    by = {}
    for o in ops:
        by.setdefault(o["outcome"], []).append(o)
    answered = by.get("answered", [])
    if answered:
        parts = [f"answered {len(answered)}/{len(ops)} reads"]
        if by.get("not implemented"):
            parts.append(f"501: {_names(by['not implemented'])}")
        others = by.get("error", []) + by.get("refused", []) + by.get("no answer", [])
        if others:
            parts.append(f"other: {_with_code(others)}")
        return "answered", "; ".join(parts)
    refused = by.get("refused", [])
    not_impl = by.get("not implemented", [])
    if len(refused) + len(not_impl) == len(ops):
        if refused and not not_impl:
            names = sorted({m["signing_name"] for m in model_results if m.get("ops")})
            return "not implemented", f"not implemented: no service registered for {', '.join(names)}"
        if not_impl and not refused:
            return "not implemented", f"not implemented: every read 501 ({len(ops)})"
        return "not implemented", f"not implemented: {len(not_impl)} reads 501, {len(refused)} refused"
    failed = [o for o in ops if o["outcome"] in ("error", "no answer")]
    return "failed", f"failed: {_with_code(failed)}"


def table_text(table):
    """The table as written: one line per service and per operation, so a change reads as a short diff."""
    def one(o):
        return json.dumps(o, separators=(", ", ": "))

    lines = ["{"]
    for k in table:
        if k in ("services", "models"):
            continue
        lines.append(f" {json.dumps(k)}: {one(table[k])},")
    lines.append(' "services": [')
    lines.append(",\n".join("  " + one(s) for s in table["services"]))
    lines.append(" ],")
    lines.append(' "models": {')
    blocks = []
    for name in sorted(table.get("models", {})):
        m = table["models"][name]
        head = {k: v for k, v in m.items() if k != "ops"}
        if "ops" not in m:
            blocks.append(f"  {json.dumps(name)}: {one(head)}")
            continue
        inner = one(head)[:-1]
        ops = ",\n".join("    " + one(o) for o in m["ops"])
        blocks.append(f"  {json.dumps(name)}: {inner}, \"ops\": [\n{ops}\n  ]}}" if m["ops"]
                      else f"  {json.dumps(name)}: {inner}, \"ops\": []}}")
    lines.append(",\n".join(blocks))
    lines.append(" }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def write_table(table, path=TABLE):
    path = pathlib.Path(path)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(table_text(table))
    json.loads(tmp.read_text())  # the text is the table
    tmp.replace(path)
